def kl_residual_nmf(
    X,
    n_components=None,
    *,
    W_init=None,
    H_init=None,
    normalize_W=True,
    update="both",
    max_iter=300,
    tol=1e-5,
    eps=1e-10,
    max_backtracking=40,
    random_state=None,
    verbose=False,
):
    """
    NMF minimizing the squared Frobenius norm of the element-wise
    generalized KL-divergence residual.

    Objective
    ---------
        min 0.5 * ||X * log(X / (W @ H))
                      - X + W @ H||_F^2

    Subject to
    ----------
        W >= 0
        H >= 0

    Parameters
    ----------
    X : ndarray, shape (n_features, n_frames)
        Nonnegative input matrix.

    n_components : int, optional
        Number of components. Can be inferred from initial matrices.

    W_init : ndarray, optional
        Initial basis matrix, shape (n_features, n_components).

    H_init : ndarray, optional
        Initial activation matrix, shape (n_components, n_frames).

    update : {'both', 'W', 'H'}
        'both': optimize W and H alternately.
        'W': optimize W while keeping H fixed.
        'H': optimize H while keeping W fixed.

    max_iter : int
        Maximum number of outer iterations.

    tol : float
        Relative objective-change stopping tolerance.

    eps : float
        Numerical stabilization constant. Also added to W @ H
        when evaluating the divergence.

    max_backtracking : int
        Maximum line-search attempts per block update.

    random_state : int, optional
        Random seed.

    verbose : bool
        Print iteration information.

    Returns
    -------
    W : ndarray
        Learned basis matrix.

    H : ndarray
        Learned activation matrix.

    history : list of dict
        Objective, divergence and update information.
    """
    def project_simplex_columns(A):
        """
        Euclidean projection of each column onto:
            {x >= 0 : sum(x) = 1}
        """
        U = np.sort(A, axis=0)[::-1]
        cssv = np.cumsum(U, axis=0) - 1.0

        indices = np.arange(1, A.shape[0] + 1)[:, None]

        condition = U - cssv / indices > 0
        rho = condition.sum(axis=0) - 1

        theta = (
            cssv[rho, np.arange(A.shape[1])]
            / (rho + 1)
        )

        return np.maximum(A - theta[None, :], 0.0)
    def evaluate(W, H, need_gradient=False):

            Y = W @ H + eps

            positive = X > 0

            E = Y.copy()

            # E = X * log(X/Y) - X + Y.
            E[positive] = (
                X[positive] * np.log(X[positive] / Y[positive])
                - X[positive]
                + Y[positive]
            )

            # Protect against tiny negative round-off errors.
            np.maximum(E, 0.0, out=E)

            objective = 0.5 * np.sum(E * E)

            if not need_gradient:
                return objective

            # Gradient with respect to Y.
            G = E * (1.0 - X / Y)

            # Curvature with respect to Y.
            curvature = (
                (1.0 - X / Y) ** 2
                + E * X / (Y * Y)
            )

            return objective, G, float(np.max(curvature))

    # ---------------------------------------------------------
    # Validation
    # ---------------------------------------------------------
    X = np.asarray(X, dtype=np.float64)

    if X.ndim != 2 or min(X.shape) == 0:
        raise ValueError("X must be a non-empty 2D matrix.")

    if not np.all(np.isfinite(X)) or np.any(X < 0):
        raise ValueError("X must be finite and nonnegative.")

    if update not in {"both", "W", "H"}:
        raise ValueError("update must be 'both', 'W', or 'H'.")

    if max_iter < 1 or max_backtracking < 1:
        raise ValueError("Iteration limits must be positive.")

    if tol < 0 or eps <= 0:
        raise ValueError("tol must be nonnegative and eps positive.")

    F, T = X.shape

    # ---------------------------------------------------------
    # Infer rank
    # ---------------------------------------------------------

    inferred = []

    if W_init is not None:
        W_init = np.asarray(W_init, dtype=np.float64)

        if W_init.ndim != 2:
            raise ValueError("W_init must be 2D.")

        inferred.append(W_init.shape[1])

    if H_init is not None:
        H_init = np.asarray(H_init, dtype=np.float64)

        if H_init.ndim != 2:
            raise ValueError("H_init must be 2D.")

        inferred.append(H_init.shape[0])

    if n_components is None:
        if not inferred:
            raise ValueError(
                "Specify n_components or provide W_init/H_init."
            )
        n_components = inferred[0]

    if not isinstance(n_components, (int, np.integer)) \
            or n_components <= 0:
        raise ValueError("n_components must be positive.")

    K = int(n_components)

    if any(k != K for k in inferred):
        raise ValueError("Initialization matrices have incompatible ranks.")

    rng = np.random.default_rng(random_state)

    # ---------------------------------------------------------
    # Initialize H first
    # ---------------------------------------------------------

    if H_init is not None:
        H = np.asarray(H_init, dtype=np.float64).copy()

        if H.ndim != 2 or not np.all(np.isfinite(H)):
            raise ValueError("Invalid H_init.")

        if np.any(H < 0):
            raise ValueError("H_init must be nonnegative.")

        if H.shape[1] != T:
            raise ValueError("H_init has an incorrect number of frames.")

        if n_components is not None and H.shape[0] != n_components:
            raise ValueError("H_init has an incorrect component count.")

        K = H.shape[0]
    else:
        if update == "W":
            raise ValueError("H_init is required when update='W'.")

        K = int(n_components)
        H = rng.random((K, T)) + eps

    # ---------------------------------------------------------
    # Initialize W
    # ---------------------------------------------------------

    if W_init is not None:
        W = np.asarray(W_init, dtype=np.float64).copy()

        if W.shape != (F, K):
            raise ValueError("W_init has an incorrect shape.")

        if not np.all(np.isfinite(W)) or np.any(W < 0):
            raise ValueError("W_init must be finite and nonnegative.")

    elif update == "W":
        # Ridge-regularized least-squares initialization:
        #
        # W = X H.T (H H.T + ridge I)^(-1)

        HH = H @ H.T
        XH = X @ H.T

        ridge = 1e-8 * max(
            np.trace(HH) / max(K, 1),
            1.0
        )

        W = np.linalg.solve(
            HH + ridge * np.eye(K),
            XH.T
        ).T

        W = np.maximum(W, eps)

    else:
        W = rng.random((F, K)) + eps

    # ---------------------------------------------------------
    # Normalize W if requested
    # ---------------------------------------------------------

    if normalize_W and update in {"both", "W"}:

        W_scale = W.sum(axis=0)

        if np.any(W_scale <= eps):
            raise ValueError("W contains zero columns.")

        W /= W_scale[None, :]

        # Preserve the initial reconstruction only if H is allowed
        # to change.
        if update == "both" and H_init is not None:
            H *= W_scale[:, None]
        # ---------------------------------------------------------
        # Divergence and gradient
        # ---------------------------------------------------------

    # ---------------------------------------------------------
    # Spectral norm squared of a Gram matrix
    # ---------------------------------------------------------

    def spectral_norm_squared(A):

        if A.shape[0] == 0:
            return eps

        eigenvalues = np.linalg.eigvalsh(A)

        return max(float(eigenvalues[-1]), eps)

    # ---------------------------------------------------------
    # Initialize block-specific step sizes
    # ---------------------------------------------------------

    initial_loss, G, curvature_max = evaluate(
        W, H, need_gradient=True
    )

    def spectral_norm_squared(A):
        return max(
            float(np.linalg.eigvalsh(A)[-1]),
            eps
        )

    L_W = spectral_norm_squared(H @ H.T)
    L_H = spectral_norm_squared(W.T @ W)

    # ---------------------------------------------------------
    # Optimization helpers
    # ---------------------------------------------------------

    def update_block(variable, block):

        nonlocal L_W, L_H

        current_loss, G, curvature_max = evaluate(
            W, H, need_gradient=True
        )

        if block == "W":

            gradient = G @ H.T
            gram = H @ H.T
            L = L_W

            old = variable

        else:

            gradient = W.T @ G
            gram = W.T @ W
            L = L_H

            old = variable

        # Improve initial Lipschitz estimate.
        L = max(L, eps)
        accepted = False
        candidate_loss = current_loss

        for bt in range(max_backtracking):

            candidate = old - gradient / L

            if normalize_W:
                candidate = project_simplex_columns(candidate)
            else:
                candidate = np.maximum(candidate, 0.0)

            delta = candidate - old

            delta_norm_sq = np.sum(delta * delta)

            if delta_norm_sq <= eps**2:
                accepted = True
                break

            if block == "W":
                candidate_loss = evaluate(candidate, H)
            else:
                candidate_loss = evaluate(W, candidate)

            # Quadratic majorization condition.
            upper_bound = (
                current_loss
                + np.sum(gradient * delta)
                + 0.5 * L * delta_norm_sq
            )

            tolerance = 1e-12 * max(1.0, abs(current_loss))

            if (
                np.isfinite(candidate_loss)
                and candidate_loss <= upper_bound + tolerance
                and candidate_loss <= current_loss + tolerance
            ):
                accepted = True
                break

            L *= 2.0

        if accepted:

            # Store the accepted step size for the next iteration.
            if block == "W":
                L_W = L
            else:
                L_H = L

            return candidate, True, L, float(candidate_loss)

        return old, False, L, float(current_loss)

    # ---------------------------------------------------------
    # Main optimization loop
    # ---------------------------------------------------------

    history = []
    previous_loss = None

    for iteration in range(1, max_iter + 1):

        W_old = W.copy()
        H_old = H.copy()

        accepted_W = False
        accepted_H = False

        # Update H.
        if update in {"both", "H"}:

            H, accepted_H, L_H, _ = update_block(
                H, "H"
            )

        # Update W.
        if update in {"both", "W"}:

            W, accepted_W, L_W, _ = update_block(
                W, "W"
            )

        # Evaluate complete objective.
        loss = evaluate(W, H)

        divergence = np.sqrt(2.0 * loss)

        relative_change = None

        if previous_loss is not None:

            relative_change = (
                abs(previous_loss - loss)
                / max(abs(previous_loss), eps)
            )

        W_change = np.linalg.norm(W - W_old)
        H_change = np.linalg.norm(H - H_old)

        history.append({
            "iteration": iteration,
            "objective": loss,
            "divergence": divergence,
            "relative_change": relative_change,
            "W_change": W_change,
            "H_change": H_change,
            "W_step_size": L_W,
            "H_step_size": L_H,
            "W_updated": accepted_W,
            "H_updated": accepted_H,
        })

        if verbose:
            print(
                f"Iter {iteration:4d}/{max_iter} | "
                f"D={divergence:.6e} | "
                f"J={loss:.6e} | "
                f"rel={relative_change if relative_change is not None else np.nan:.3e} | "
                f"dW={W_change:.3e} | "
                f"dH={H_change:.3e}"
            )

        if (
            previous_loss is not None
            and relative_change < tol
        ):
            break

        previous_loss = loss

    return W, H, history

def norm_log(H, gamma=5):
    return np.log1p(gamma * H)

def build_W0(
    sr,
    bins_per_octave,
    n_bins,
    fmin,
    n_harmonics=10,
    decay=1.0,
    sigma=1.5,
    inharmonicity=0.0,
):
    # CQT frequency grid: must match your spectrogram
    freqs = librosa.cqt_frequencies(
        n_bins=n_bins,
        fmin=fmin,
        bins_per_octave=bins_per_octave,
    )

    # Log-frequency coordinates corresponding to CQT bins
    log_freqs = np.log2(freqs)
    k = np.arange(n_bins, dtype=float)

    # Piano pitches: MIDI 21 (A0) through MIDI 108 (C8)
    midi_notes = np.arange(21, 109)

    W0 = np.zeros((n_bins, len(midi_notes)), dtype=float)

    f_max = min(freqs[-1], sr / 2.0)

    for i, m in enumerate(midi_notes):
        f0 = librosa.midi_to_hz(m)
        template = np.zeros(n_bins, dtype=float)

        for h in range(1, n_harmonics + 1):

            # Harmonic frequency, optionally including piano
            # string inharmonicity.
            fh = h * f0 * np.sqrt(
                (1.0 + inharmonicity * h**2)
                / (1.0 + inharmonicity)
            )

            # CRITICAL FIX:
            # Never map out-of-range harmonics onto the
            # first or last CQT bin.
            if fh >= f_max:
                break

            if fh < freqs[0]:
                continue

            # Fractional bin coordinate in log-frequency space
            center = np.interp(
                np.log2(fh),
                log_freqs,
                k,
            )

            # Gaussian harmonic peak
            peak = np.exp(
                -0.5 * ((k - center) / sigma) ** 2
            )

            template += peak / (h ** decay)

        # L2 normalization
        norm = np.linalg.norm(template)
        if norm > 1e-10:
            template /= norm

        W0[:, i] = template

    return W0

def build_noise_basis(n_bins, n_components=2):
    Wn = np.zeros((n_bins, n_components))

    for i in range(n_components):
        # random smooth noise shape
        x = np.random.rand(n_bins)
        x = np.convolve(x, np.hanning(15), mode='same')
        x /= np.linalg.norm(x) + 1e-10
        Wn[:, i] = x

    return Wn

def med_filter(X, sz=5):
  X_r = np.zeros(X.shape)
  for i in range(X.shape[0]):
    X_r[i,:] = scipy.ndimage.median_filter(X[i,:], size=sz, cval=0, mode='constant')
  return X_r

def enforce_min_duration(B, min_len=10):
    for q in range(B.shape[0]):
        labels, n = label(B[q])
        for i in range(1, n+1):
            if np.sum(labels == i) < min_len:
                B[q][labels == i] = 0
    return B

def midi_to_binary_matrix(
    midi_input,
    dt=0.02,                     # time quantum in seconds
    pitch_range=(21, 108),  # A0–C8 by default
    min_overlap=0.5         # fraction of frame that must be covered
):
    """
    Convert MIDI to binary (88 x T) note activation matrix using fixed time grid.

    A note is active in a frame if it overlaps the frame
    by at least min_overlap * dt.
    """

    if dt <= 0:
        raise ValueError("dt must be positive (seconds)")

    # Load MIDI
    if isinstance(midi_input, pretty_midi.PrettyMIDI):
        pm = midi_input
    else:
        pm = pretty_midi.PrettyMIDI(midi_input)

    # Time axis
    total_time = pm.get_end_time()
    T = int(np.ceil(total_time / dt))
    frame_times = np.arange(T) * dt

    n_pitches = pitch_range[1] - pitch_range[0] + 1
    B = np.zeros((n_pitches, T), dtype=np.uint8)

    # Process notes
    for instrument in pm.instruments:
        if instrument.is_drum:
            continue

        for note in instrument.notes:
            if not (pitch_range[0] <= note.pitch <= pitch_range[1]):
                continue

            p = note.pitch - pitch_range[0]

            start_frame = int(np.floor(note.start / dt))
            end_frame   = int(np.ceil(note.end   / dt))

            for t in range(start_frame, min(end_frame, T)):
                frame_start = t * dt
                frame_end   = frame_start + dt

                overlap = max(
                    0.0,
                    min(note.end, frame_end) - max(note.start, frame_start)
                )

                if overlap >= min_overlap * dt:
                    B[p, t] = 1

    return B, frame_times

def evaluate_results(H_et,H):
  #H_et - reference transcription of the piece
  #H - estimated transcription of the piece
  assert H_et.shape == H.shape
  P = 0
  R = 0
  F1 = 0
  TP = 0
  FP = 0
  FN = 0
  for i in range(H_et.shape[1]):
    TP += sum(1 for t, p in zip(H_et[:,i], H[:,i]) if t == 1 and p == 1)
    FP += sum(1 for t, p in zip(H_et[:,i], H[:,i]) if t == 0 and p == 1)
    FN += sum(1 for t, p in zip(H_et[:,i], H[:,i]) if t == 1 and p == 0)
  P = TP / (TP + FP)
  R = TP / (TP + FN)
  F1 = 2 * P * R / (P + R)
  return (P,R,F1)

