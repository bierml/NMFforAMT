class BinaryGaussianHMMTrainer:

    def __init__(
        self,
        transition_smoothing=1.0,
        start_smoothing=1.0,
        variance_floor=1e-5
    ):

        if transition_smoothing < 0 or start_smoothing < 0:
            raise ValueError("Smoothing parameters must be nonnegative.")

        if variance_floor <= 0:
            raise ValueError("variance_floor must be positive.")

        self.transition_smoothing = transition_smoothing
        self.start_smoothing = start_smoothing
        self.variance_floor = variance_floor

        # HMM initial-state counts
        self.start_counts = np.zeros(2, dtype=np.float64)

        # HMM transition counts
        self.transition_counts = np.zeros((2, 2), dtype=np.float64)

        # Number of observations belonging to each state
        self.state_counts = np.zeros(2, dtype=np.int64)

        # Running Gaussian statistics
        self.means = None
        self.M2 = None

        # Feature dimensionality
        self.n_features = None

        # Number of processed recordings
        self.n_sequences = 0

    # ==================================================
    # Add a new recording to the training dataset
    # ==================================================

    def update(self, X, y, lengths=None):

        X = np.asarray(X, dtype=np.float64)
        y = np.asarray(y).ravel()

        if X.ndim != 2:
            raise ValueError("X must be a 2D array.")

        if len(X) != len(y):
            raise ValueError("X and y must have the same number of frames.")

        if len(y) == 0:
            raise ValueError("Empty sequence.")

        if not np.all(np.isfinite(X)):
            raise ValueError("X contains NaN or infinite values.")

        if not np.all(np.isin(y, [0, 1])):
            raise ValueError("y must contain only 0 and 1.")

        y = y.astype(int)

        T, n_features = X.shape

        # ----------------------------------------------
        # Sequence lengths
        # ----------------------------------------------

        if lengths is None:
            lengths = np.array([T], dtype=int)
        else:
            raw_lengths = np.asarray(lengths)

            if (
                raw_lengths.ndim != 1
                or not np.all(np.isfinite(raw_lengths))
                or np.any(raw_lengths != np.floor(raw_lengths))
            ):
                raise ValueError("Invalid sequence lengths.")

            lengths = raw_lengths.astype(int)

        if (
            len(lengths) == 0
            or np.any(lengths <= 0)
            or np.sum(lengths) != T
        ):
            raise ValueError("Invalid sequence lengths.")

        # ----------------------------------------------
        # Initialize feature statistics
        # ----------------------------------------------

        if self.n_features is None:

            self.n_features = n_features

            self.means = np.zeros(
                (2, n_features),
                dtype=np.float64
            )

            self.M2 = np.zeros(
                (2, n_features),
                dtype=np.float64
            )

        elif self.n_features != n_features:

            raise ValueError(
                f"Expected {self.n_features} features, "
                f"got {n_features}."
            )

        # ----------------------------------------------
        # 1. Initial-state and transition counts
        # ----------------------------------------------

        offset = 0

        for L in lengths:

            ys = y[offset:offset + L]

            # Initial state
            self.start_counts[ys[0]] += 1

            # Transitions
            if L > 1:

                np.add.at(
                    self.transition_counts,
                    (ys[:-1], ys[1:]),
                    1
                )

            offset += L

        # ----------------------------------------------
        # 2. Update Gaussian emission statistics
        # ----------------------------------------------

        for state in (0, 1):

            X_state = X[y == state]

            batch_n = len(X_state)

            if batch_n == 0:
                continue

            # Statistics of the current recording
            batch_mean = np.mean(X_state, axis=0)

            centered = X_state - batch_mean

            batch_M2 = np.sum(
                centered ** 2,
                axis=0
            )

            # Statistics accumulated from previous recordings
            old_n = self.state_counts[state]

            new_n = old_n + batch_n

            if old_n == 0:

                self.means[state] = batch_mean
                self.M2[state] = batch_M2

            else:

                delta = batch_mean - self.means[state]

                self.means[state] += (
                    delta * batch_n / new_n
                )

                self.M2[state] += (
                    batch_M2
                    + delta ** 2 * old_n * batch_n / new_n
                )

            self.state_counts[state] = new_n

        self.n_sequences += len(lengths)

        return self

    # ==================================================
    # Construct an HMM using accumulated statistics
    # ==================================================

    def get_model(self):

        if self.n_features is None:
            raise ValueError("No training data has been added.")

        if np.any(self.state_counts == 0):

            raise ValueError(
                "Both states must occur in the training dataset. "
                f"State counts: {self.state_counts}"
            )

        # ----------------------------------------------
        # Initial probabilities
        # ----------------------------------------------

        startprob = (
            self.start_counts + self.start_smoothing
        )

        if startprob.sum() == 0:
            raise ValueError("No initial-state observations.")

        startprob /= startprob.sum()

        # ----------------------------------------------
        # Transition probabilities
        # ----------------------------------------------

        transmat = (
            self.transition_counts + self.transition_smoothing
        )

        row_sums = transmat.sum(axis=1, keepdims=True)

        if np.any(row_sums == 0):
            raise ValueError(
                "A state has no outgoing transitions. "
                "Increase transition_smoothing."
            )

        transmat /= row_sums

        # ----------------------------------------------
        # Gaussian means and diagonal covariances
        # ----------------------------------------------

        means = self.means.copy()

        # Maximum-likelihood variance estimates
        covars = (
            self.M2 /
            self.state_counts[:, None]
        )

        covars = np.maximum(
            covars,
            self.variance_floor
        )

        # ----------------------------------------------
        # Construct GaussianHMM
        # ----------------------------------------------

        model = GaussianHMM(
            n_components=2,
            covariance_type="diag",
            algorithm="viterbi",
            init_params="",
            params=""
        )

        model.n_features = self.n_features

        model.startprob_ = startprob
        model.transmat_ = transmat
        model.means_ = means
        model.covars_ = covars

        return model

